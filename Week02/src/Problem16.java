public class Problem16{
    public static void main(String[] args) {
        int x;
        x = 5;
        System.out.println("Current value of x is: " + x);
        x += 10;
        System.out.println("After x += 10: " + x);
        x -= 10;
        System.out.println("After x -= 10: " + x);
        x++;
        System.out.println("After x++: " + x);
        x--;
        System.out.println("After x--: " + x);
    }
}